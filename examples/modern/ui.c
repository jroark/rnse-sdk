static int width(char ch) {
    return ch == ' '                                          ? 4
           : ch == 'i' || ch == 'l' || ch == '.' || ch == ':' ? 4
                                                              : 6;
}
static void text(int x, int y, const char *s, u8 c, int scale, int top,
                 int bottom) {
    int k, r, b, xx, yy;
    if (scale < 1 || scale > 4)
        return;
    for (k = 0; s[k] && k < 96; k++) {
        unsigned ch = (unsigned char)s[k];
        if (x + 6 * scale > 392) {
            if (x + 3 * scale <= 400)
                for (b = 0; b < 3; b++)
                    screen_fill(x + b * scale, y + 6 * scale, 1, 1, c);
            break;
        }
        if (ch >= 32 && ch < 127)
            for (r = 0; r < 7; r++)
                for (b = 0; b < 5; b++)
                    if (font[ch - 32][r] & (16 >> b))
                        for (yy = 0; yy < scale; yy++)
                            for (xx = 0; xx < scale; xx++)
                                if (y + r * scale + yy >= top &&
                                    y + r * scale + yy < bottom &&
                                    x + b * scale + xx >= 0)
                                    screen_pixel(x + b * scale + xx,
                                                 y + r * scale + yy, c);
        x += width((char)ch) * scale;
    }
}
void ui_text(int x, int y, const char *s, u8 c, int scale) {
    text(x, y, s, c, scale, 0, 235);
}
void ui_app_fill(int x, int y, int w, int h, u8 c) {
    if (x < 0) {
        w += x;
        x = 0;
    }
    if (y < 0) {
        h += y;
        y = 0;
    }
    if (x >= 400 || y >= 136)
        return;
    if (w > 400 - x)
        w = 400 - x;
    if (h > 136 - y)
        h = 136 - y;
    if (w > 0 && h > 0)
        screen_fill(x, y + 60, w, h, c < 5 ? c : 1);
}
void ui_app_text(int x, int y, const char *s, u8 c, int scale) {
    text(x, y + 60, s, c < 5 ? c : 1, scale, 60, 196);
}
void ui_number(char *p, int n) {
    char t[12];
    int i = 0;
    u32 v;
    if (n < 0) {
        *p++ = '-';
        v = 0u - (u32)n;
    } else
        v = n;
    do {
        t[i++] = '0' + umod(v, 10);
        v = udiv(v, 10);
    } while (v);
    while (i)
        *p++ = t[--i];
    *p = 0;
}
void ui_frame(const char *title, const char *tl, const char *tr, const char *bl,
              const char *br, int volume) {
    char n[12];
    screen_fill(0, 0, 400, 235, 0);
    screen_fill(0, 0, 400, 39, 4);
    ui_text(14, 13, title, 1, 2);
    ui_number(n, volume);
    ui_text(324, 16, "Vol", 2, 1);
    ui_text(350, 13, n, 1, 2);
    screen_fill(0, 38, 400, 2, 3);
    screen_fill(0, 197, 400, 38, 4);
    ui_text(12, 46, tl, 2, 1);
    ui_text(272, 46, tr, 2, 1);
    ui_text(12, 213, bl, 1, 1);
    ui_text(272, 213, br, 1, 1);
}
void ui_row(int row, const char *s, int selected) {
    int y = 65 + row * 25;
    screen_fill(8, y - 5, 384, 24, selected ? 3 : 0);
    ui_text(17, y, s, 1, 2);
}
